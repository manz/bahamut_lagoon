# Battle opcodes: utils.vm.battle_script.OPS names them and gives their operands, docs/vm/battle_opcodes.md has what
# each does.


def _battle_opcode(op: int) -> OpcodeProtocol:
    name, kinds = battle_script.name(op), battle_script.kinds(op)
    if name == "jump":
        return Jump()
    if name in battle_script.CALLS:
        return JumpToSubRoutine()
    if name == "return":
        return ReturnFromSubRoutine()
    if name in battle_script.JUMPS:
        return ConditionalJump(len(kinds) - 1)
    if name in battle_script.TEXTS:
        return TextOpcode()
    return Opcode(battle_script.size(op))


battle_opcode_names: dict[int, str] = {op: battle_script.name(op) for op in range(0x100)}

battle_opcode_table: OpcodeTable = {op: _battle_opcode(op) for op in range(0x100)}
